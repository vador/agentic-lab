#!/usr/bin/env bash
# Day-to-day VM operations.
source "$(dirname "$0")/../lib/common.sh"
source "$LAB_ROOT/lib/vm.sh"

usage() {
  cat <<'EOF'
Usage: lab vm <command> [args]
  list                          VMs, state and IPs
  start|stop <name>             start / gracefully shut down
  console <name>                serial console (exit with Ctrl+])
  snapshot <name> [label]       take a snapshot (do this before a long autonomous agent run)
  snapshots <name>              list snapshots
  rollback <name> <label>       revert to a snapshot
  rmsnap <name> <label>         delete a snapshot
  destroy <name> [--yes]        delete VM, its disk, IP reservation and SSH entries
  ssh-config                    regenerate ~/.ssh/config.d/agentlab
  golden-list                   golden images and which VMs use them
EOF
}

dom() { echo "$VM_PREFIX$1"; }

ssh_config() {
  mkdir -p ~/.ssh/config.d
  chmod 700 ~/.ssh
  local f=~/.ssh/config.d/agentlab name ip
  {
    echo "# Generated by agentlab (lab vm ssh-config) — do not edit"
    while IFS='|' read -r name ip; do
      [[ -n $name ]] || continue
      cat <<EOF

Host $name $name.$LAB_DOMAIN
  HostName $ip
  User $VM_USER
  UserKnownHostsFile ~/.ssh/known_hosts.agentlab
  StrictHostKeyChecking accept-new
  ServerAliveInterval 30
EOF
    done < <(reserved_hosts)
    cat <<EOF

Host gitea.$LAB_DOMAIN
  Port $GITEA_SSH_PORT
  User git
EOF
  } >"$f"
  chmod 600 "$f"
  touch ~/.ssh/config
  if ! grep -q 'config.d/agentlab' ~/.ssh/config; then
    # Include must come before any Host block
    { echo "Include config.d/agentlab"; echo; cat ~/.ssh/config; } >~/.ssh/config.new
    chmod 600 ~/.ssh/config.new
    mv ~/.ssh/config.new ~/.ssh/config
    log "Added 'Include config.d/agentlab' at the top of ~/.ssh/config"
  fi
}

cmd=${1:-help}
shift || true
case $cmd in
  list)
    vsh list --all | awk -v p="$VM_PREFIX" 'NR <= 2 || $2 ~ "^"p'
    echo
    echo "Reserved IPs:"
    reserved_hosts | sed 's/|/\t/; s/^/  /'
    ;;
  start) vsh start "$(dom "$1")" ;;
  stop) vsh shutdown "$(dom "$1")" ;;
  console) vsh console "$(dom "$1")" ;;
  snapshot)
    label=${2:-snap-$(date +%Y%m%d-%H%M%S)}
    vsh snapshot-create-as "$(dom "$1")" "$label" --atomic >/dev/null
    log "Snapshot '$label' of $1 created"
    ;;
  snapshots) vsh snapshot-list "$(dom "$1")" ;;
  rollback)
    [[ -n ${2:-} ]] || die "usage: lab vm rollback <name> <label>"
    vsh snapshot-revert "$(dom "$1")" "$2"
    log "$1 reverted to '$2'"
    ;;
  rmsnap) vsh snapshot-delete "$(dom "$1")" "$2" ;;
  destroy)
    name=${1:?name required}
    d=$(dom "$name")
    vsh dominfo "$d" >/dev/null 2>&1 || die "no VM $d"
    [[ ${2:-} == --yes ]] || confirm "Really destroy $d and its disk?" || exit 1
    mac=$(vsh domiflist "$d" | awk -v n="$LAB_NET_NAME" '$3 == n {print $5}')
    ip=$(reserved_hosts | awk -F'|' -v n="$name" '$1 == n {print $2}')
    if [[ $(vsh domstate "$d") == running ]]; then vsh destroy "$d" >/dev/null; fi
    for s in $(vsh snapshot-list "$d" --name 2>/dev/null); do vsh snapshot-delete "$d" "$s" >/dev/null; done
    vsh undefine "$d" --remove-all-storage >/dev/null
    if [[ -n $mac && -n $ip ]]; then
      vsh net-update "$LAB_NET_NAME" delete ip-dhcp-host "<host mac='$mac' name='$name' ip='$ip'/>" --live --config >/dev/null || true
      ssh-keygen -R "$ip" -f ~/.ssh/known_hosts.agentlab >/dev/null 2>&1 || true
    fi
    ssh_config
    log "$d destroyed"
    ;;
  ssh-config) ssh_config ;;
  golden-list)
    for g in $(vsh vol-list --pool "$LAB_POOL_NAME" | awk '$1 ~ /^golden-/ {print $1}'); do
      users=$(for v in $(vsh vol-list --pool "$LAB_POOL_NAME" | awk -v p="$VM_PREFIX" '$1 ~ "^"p {print $1}'); do
        vsh vol-dumpxml --pool "$LAB_POOL_NAME" "$v" | grep -q "/$g<" && echo -n "${v%.qcow2} "
      done)
      echo "$g  used by: ${users:-(none — safe to delete: virsh vol-delete --pool $LAB_POOL_NAME $g)}"
    done
    ;;
  help | -h | --help) usage ;;
  *) usage; exit 1 ;;
esac
